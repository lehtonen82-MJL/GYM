#!/usr/bin/env bash
# Applies supabase/setup.sql to a throwaway local Postgres and checks that it
#   1. builds a fresh database,
#   2. can be re-run (idempotent),
#   3. keeps existing data on re-run and computes PRs per tool,
#   4. matches the committed snapshot supabase/schema.sql (unless --update-snapshot).
#
# Needs psql + pg_dump and a local Postgres you can create databases on, e.g.
#   PGHOST=127.0.0.1 PGPORT=5432 PGUSER=postgres supabase/tests/verify-migrations.sh
# Never point this at a real Supabase project: it drops and recreates $DB.
set -euo pipefail

cd "$(dirname "$0")/.."
DB="${VERIFY_DB:-gym_migration_test}"
PSQL=(psql -X -q -v ON_ERROR_STOP=1)
UPDATE_SNAPSHOT=false
[[ "${1:-}" == "--update-snapshot" ]] && UPDATE_SNAPSHOT=true

node ../scripts/build-supabase-setup.mjs >/dev/null

"${PSQL[@]}" -d postgres -c "DROP DATABASE IF EXISTS $DB" -c "CREATE DATABASE $DB"
"${PSQL[@]}" -d "$DB" -f tests/supabase_stub.sql

echo "1/4 fresh database"
"${PSQL[@]}" -d "$DB" -f setup.sql >/dev/null

echo "2/4 re-run on itself"
"${PSQL[@]}" -d "$DB" -f setup.sql >/dev/null

echo "3/4 re-run with data"
"${PSQL[@]}" -d "$DB" -f tests/fixture.sql
"${PSQL[@]}" -d "$DB" -f setup.sql >/dev/null
result=$("${PSQL[@]}" -d "$DB" -tA -c "
  SELECT
    (SELECT count(*) FROM set_entries) || ' sets, ' ||
    (SELECT count(*) FROM exercise_definitions) || ' definitions, linked=' ||
    (SELECT (exercise_definition_id IS NOT NULL)::text FROM exercises) || ', prs=' ||
    (SELECT string_agg(equipment_type || ':' || pr_type || '=' || value, ' ' ORDER BY equipment_type, pr_type)
       FROM exercise_prs)")
echo "   $result"
expected="3 sets, 115 definitions, linked=true, prs=barbell:1rm_estimate=116.67 barbell:max_volume=1000.00 barbell:max_weight=100.00 dumbbell:1rm_estimate=45.60 dumbbell:max_volume=288.00 dumbbell:max_weight=36.00"
if [[ "$result" != "$expected" ]]; then
  echo "FAIL: expected $expected" >&2
  exit 1
fi

echo "4/4 schema snapshot"
"${PSQL[@]}" -d "$DB" -c "TRUNCATE auth.users CASCADE"
snapshot=$(mktemp)
{
  echo "-- ============================================================"
  echo "-- GYM Tracker: schema snapshot (public schema)"
  echo "--"
  echo "-- GENERATED by supabase/tests/verify-migrations.sh --update-snapshot."
  echo "-- Reference only — do NOT run this file. To set up or update a"
  echo "-- database run supabase/setup.sql (see supabase/migrations/README.md)."
  echo "-- ============================================================"
  echo
  pg_dump --schema-only --no-owner --no-privileges --schema=public "$DB" \
    | grep -v -E '^-- Dumped (from|by)|^\\(un)?restrict ' \
    | cat -s
} > "$snapshot"

if $UPDATE_SNAPSHOT; then
  mv "$snapshot" schema.sql
  echo "   schema.sql updated"
elif ! diff -u schema.sql "$snapshot"; then
  rm -f "$snapshot"
  echo "FAIL: schema.sql is out of date — run with --update-snapshot and commit it" >&2
  exit 1
else
  rm -f "$snapshot"
  echo "   schema.sql matches"
fi

"${PSQL[@]}" -d postgres -c "DROP DATABASE $DB"
echo "OK"
