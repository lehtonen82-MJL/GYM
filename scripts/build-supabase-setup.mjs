// Builds supabase/setup.sql: every migration in order + seed.sql, in one transaction.
// Paste the result into the Supabase SQL Editor to create OR update a database —
// every migration is re-runnable, so running it on an existing project is safe.
//
//   npm run db:setup
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../supabase/", import.meta.url).pathname;
const migrationsDir = join(root, "migrations");

const migrations = readdirSync(migrationsDir)
  .filter((f) => /^\d{3}[a-z]?_.+\.sql$/.test(f))
  .sort();

const parts = [
  `-- ============================================================
-- GYM Tracker: full database setup / update
--
-- GENERATED by scripts/build-supabase-setup.mjs — do not edit by hand.
-- Source of truth: supabase/migrations/*.sql + supabase/seed.sql
--
-- Supabase → SQL Editor → New query → paste this file → Run.
-- Safe on a new project and on an existing one (all steps are
-- re-runnable). Runs in one transaction: any error rolls back everything.
--
-- Migrations: ${migrations.length} (${migrations[0]} … ${migrations[migrations.length - 1]})
-- ============================================================

BEGIN;
`,
  ...migrations.map(
    (f) => `\n-- >>>>>>>>>> migrations/${f}\n\n${readFileSync(join(migrationsDir, f), "utf8").trimEnd()}\n`
  ),
  `\n-- >>>>>>>>>> seed.sql\n\n${readFileSync(join(root, "seed.sql"), "utf8").trimEnd()}\n`,
  "\nCOMMIT;\n",
];

writeFileSync(join(root, "setup.sql"), parts.join(""));
console.log(`supabase/setup.sql: ${migrations.length} migrations + seed.sql`);
